export function trigramByXiantian(n: number): Trigram {
  const i = n % 8 === 0 ? 7 : (n % 8) - 1;
  return TRIGRAMS[XIANTIAN_BY_NUM[i]];
}

export function bitsToTrigram(bits: [LineBit, LineBit, LineBit]): Trigram {
  const key = (Object.keys(TRIGRAMS) as TrigramKey[]).find((k) => TRIGRAMS[k].bits.join("") === bits.join(""));
  return TRIGRAMS[key ?? "坤"];
}

