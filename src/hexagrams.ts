function bitsFromTrigrams(lower: TrigramKey, upper: TrigramKey): Hexagram["bits"] {
  const l = TRIGRAMS[lower].bits;
  const u = TRIGRAMS[upper].bits;
  return [l[0], l[1], l[2], u[0], u[1], u[2]];
}

export const HEXAGRAMS: Hexagram[] = KING_WEN.map(([id, name, alias, upper, lower, judgment, image, lines]) => ({
  id,
  name,
  alias,
  unicode: String.fromCodePoint(0x4dc0 + id - 1),
  upper,
  lower,
  bits: bitsFromTrigrams(lower, upper),
  judgment,
  image,
  lines,
}));

const BY_BITS = new Map(HEXAGRAMS.map((h) => [h.bits.join(""), h]));
const BY_ID = new Map(HEXAGRAMS.map((h) => [h.id, h]));
const BY_NAME = new Map(HEXAGRAMS.map((h) => [h.name, h]));

export function hexagramFromBits(bits: LineBit[]): Hexagram {
  const key = bits.slice(0, 6).join("");
  return BY_BITS.get(key) ?? HEXAGRAMS[1];
}

export function hexagramById(id: number): Hexagram {
  return BY_ID.get(id) ?? HEXAGRAMS[0];
}

export function hexagramByName(name: string): Hexagram | undefined {
  return BY_NAME.get(name.replace(/卦$/, ""));
}

export const LINE_NAMES = ["初", "二", "三", "四", "五", "上"] as const;

export function lineTitle(index: number, yang: boolean): string {
  const pos = LINE_NAMES[index];
  if (index === 0) return yang ? "初九" : "初六";
  if (index === 5) return yang ? "上九" : "上六";
  return yang ? `九${pos}` : `六${pos}`;
}

export const PALACE_ORDER: TrigramKey[] = ["乾", "兑", "离", "震", "巽", "坎", "艮", "坤"];

function flip(bit: LineBit): LineBit {
  return bit === 1 ? 0 : 1;
}

function palaceHexagrams(palace: TrigramKey): Hexagram[] {
  const root = bitsFromTrigrams(palace, palace);
  const seq: LineBit[][] = [root.slice() as LineBit[]];
  const cur = root.slice() as LineBit[];
  for (let i = 0; i < 5; i++) {
    cur[i] = flip(cur[i]);
    seq.push(cur.slice());
  }
  const youhun = seq[5].slice();
  youhun[3] = flip(youhun[3]);
  seq.push(youhun);
  const guihun = youhun.slice();
  guihun[0] = root[0];
  guihun[1] = root[1];
  guihun[2] = root[2];
  seq.push(guihun);
  return seq.map((bits) => hexagramFromBits(bits));
}

export const GONG_SHI: Record<number, number> = {
  0: 5,
  1: 0,
  2: 1,
  3: 2,
  4: 3,
  5: 4,
  6: 3,
  7: 2,
};

export type PalaceInfo = {
  palace: TrigramKey;
  palaceWuxing: Trigram["wuxing"];
  generation: number;
  generationName: string;
  shi: number;
  ying: number;
};

const GENERATION_NAMES = ["本宫", "一世", "二世", "三世", "四世", "五世", "游魂", "归魂"];

const PALACE_LOOKUP = new Map<string, PalaceInfo>();
for (const palace of PALACE_ORDER) {
  palaceHexagrams(palace).forEach((hex, gen) => {
    const shi = GONG_SHI[gen];
    PALACE_LOOKUP.set(hex.bits.join(""), {
      palace,
      palaceWuxing: TRIGRAMS[palace].wuxing,
      generation: gen,
      generationName: GENERATION_NAMES[gen],
      shi,
      ying: (shi + 3) % 6,
    });
  });
}

export function palaceOf(bits: LineBit[]): PalaceInfo {
  return PALACE_LOOKUP.get(bits.slice(0, 6).join("")) ?? {
    palace: "坤",
    palaceWuxing: "土",
    generation: 0,
    generationName: "本宫",
    shi: 5,
    ying: 2,
  };
}
